const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const { createApp } = require('../server');
const waitFor = async check => { for(let i=0;i<150;i++){if(check()) return; await new Promise(r=>setTimeout(r,20));} assert.fail('Tempo excedido esperando interface'); };
test('fluxo da interface com API real e sessão antiga', async t => {
  const {app,db}=createApp({dbPath:':memory:',secret:'ui-test-secret-at-least-32-characters'});
  const server=app.listen(0);await new Promise(r=>server.once('listening',r));
  const origin=`http://127.0.0.1:${server.address().port}`;
  const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:origin,runScripts:'outside-only',pretendToBeVisual:true});
  t.after(()=>{dom.window.close();server.close();db.close();});
  const w=dom.window,d=w.document,$=id=>d.getElementById(id);
  w.fetch=(url,options)=>fetch(new URL(url,origin),options);w.AbortSignal=AbortSignal;w.confirm=()=>true;
  w.localStorage.setItem('ecorotas_user','broken JSON');
  w.eval(fs.readFileSync('community.js','utf8'));
  assert.equal($('navAuth').hidden,false);
  $('openRegisterBtn').click();assert.equal(d.activeElement.id,'regName');
  $('regName').value='Cauê Ishiki';$('regEmail').value='teste@example.com';$('regPassword').value='senha-teste-123';
  $('formRegister').dispatchEvent(new w.Event('submit',{cancelable:true}));
  await waitFor(()=>$('navUserName').textContent==='Olá, Cauê');
  assert.equal($('navAuth').hidden,true);assert.equal($('navUser').hidden,false);
  $('openProfileBtn').click();$('profileName').value='Nome Corrigido';
  $('profileForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
  await waitFor(()=>$('navUserName').textContent==='Olá, Nome');
  $('postContent').value='<img src=x onerror=alert(1)> mensagem';
  $('postForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
  await waitFor(()=>d.querySelector('.post-card p'));
  assert.equal(d.querySelector('.post-card p').textContent,'<img src=x onerror=alert(1)> mensagem');
  assert.equal(d.querySelector('.post-card img'),null);
  assert.equal(d.querySelector('.post-card b').textContent,'Nome Corrigido');
  w.localStorage.setItem('ecorotas_user',JSON.stringify({email:'teste@example.com'}));
  w.dispatchEvent(new w.StorageEvent('storage',{key:'ecorotas_user'}));
  assert.equal($('navUserName').textContent,'Meu perfil');
  await waitFor(()=>$('navUserName').textContent==='Olá, Nome');
  d.querySelector('.post-delete').click();await waitFor(()=>!d.querySelector('.post-card'));
  $('logoutBtn').click();assert.equal($('navUser').hidden,true);
  $('openLoginBtn').click();$('loginEmail').value='TESTE@example.com';$('loginPassword').value='senha-teste-123';
  $('formLogin').dispatchEvent(new w.Event('submit',{cancelable:true}));
  await waitFor(()=>$('navUser').hidden===false);
  assert.equal($('navUserName').textContent,'Olá, Nome');
});
